"""
Risk Classifier for Privilege Escalation Activity Monitor.
Assigns risk levels (High, Medium, Low), aggregates multi-rule compound risks,
and ensures a clear distinction between rule-based heuristic alerts and confirmed security incidents.
"""

from typing import List, Dict, Any, Tuple
from .rules import RuleResult


class RiskClassifier:
    """Classifies risk level based on triggered rules, incident severity, and compound correlations."""

    SEVERITY_SCORES = {
        "HIGH": 10,
        "MEDIUM": 5,
        "LOW": 2,
    }

    RISK_ORDER = ["HIGH", "MEDIUM", "LOW"]

    def __init__(self, custom_weights: Dict[str, int] = None):
        self.weights = {**self.SEVERITY_SCORES}
        if custom_weights:
            self.weights.update(custom_weights)

    def classify_event(self, triggered_rules: List[RuleResult]) -> Tuple[str, int, str]:
        """
        Evaluates a set of triggered rules for an event.
        Returns:
            (composite_risk_level, total_score, risk_summary_text)
        """
        if not triggered_rules:
            return ("NONE", 0, "No suspicious privilege escalation patterns detected.")

        # Highest risk among triggered rules
        has_high = any(r.risk_level == "HIGH" for r in triggered_rules)
        has_medium = any(r.risk_level == "MEDIUM" for r in triggered_rules)

        total_score = sum(self.weights.get(r.risk_level, 1) for r in triggered_rules)

        if has_high or total_score >= 10:
            level = "HIGH"
        elif has_medium or total_score >= 5:
            level = "MEDIUM"
        else:
            level = "LOW"

        # Compound alert summary
        rule_names = [r.rule_name for r in triggered_rules]
        if len(triggered_rules) > 1:
            summary = (
                f"COMPOUND ALERT ({level} RISK): Event triggered {len(triggered_rules)} distinct rules "
                f"({', '.join(rule_names)}). Multiple concurrent indicators significantly heighten the likelihood of unauthorized activity."
            )
        else:
            summary = f"{level} RISK: Triggered rule '{rule_names[0]}'."

        return (level, total_score, summary)

    @staticmethod
    def get_risk_badge(risk_level: str) -> str:
        """Returns colored status markdown badge for Streamlit display."""
        rl = risk_level.upper()
        if rl == "HIGH":
            return "🔴 HIGH"
        elif rl == "MEDIUM":
            return "🟡 MEDIUM"
        elif rl == "LOW":
            return "🟢 LOW"
        return "⚪ INFO"

    @staticmethod
    def get_educational_disclaimer() -> str:
        """Returns required legal & technical disclaimer distinguishing detections from confirmed incidents."""
        return (
            "⚠️ IMPORTANT AUDIT NOTICE: Detections generated by this monitor are rule-based security alerts "
            "indicating potential anomalies, policy violations, or suspicious patterns. They do NOT represent "
            "definitive proof of a malicious cyberattack. Always corroborate findings with organizational change "
            "management tickets, secondary audit sources, and direct stakeholder interviews."
        )
